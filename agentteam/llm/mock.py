    def _t_fix(self, prompt, a):
        paths = list(dict.fromkeys(re.findall(r'"files": \[\s*"([^"]+)"', prompt)))
        paths = [p for p in paths if "/" in p or "." in p][:2]
        return _files({"summary": f"Fixed issues in {', '.join(paths) or 'n/a'}", "needs_info": False},
                      {p: _content_for(p) + "# fixed\n" if p.endswith(".py") else _content_for(p) for p in paths})

