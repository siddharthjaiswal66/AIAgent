"""Deterministic offline LLM used for demos and smoke tests (LLM_PROVIDER=mock).

It does not write a real application; it exercises the entire multi-agent
workflow (team selection, consultation, ownership, change requests, QA loop)
without network access or API keys.
"""

from __future__ import annotations

