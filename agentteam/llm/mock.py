    def _t_implement_task(self, prompt, a):
        if not self._asked and "Answers from your teammates" not in a:
            self._asked = True
            return _files({"summary": "Need contract details", "needs_info": True,
                           "questions": [{"to": "solution_architect", "question": "What is the base path of the REST API?"}]}, {})
