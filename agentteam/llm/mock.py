    def __init__(self, settings):
        super().__init__(settings)
        self._asked = False
        self._qa_evaluations = 0

    async def _complete(self, system, messages, *, model, max_tokens, temperature):
        await asyncio.sleep(0.02)
        prompt = messages[0]["content"]
        match = _TASK_RE.search(prompt)
        task = match.group(1) if match else "answer_question"
        assignment = prompt.split("## Your assignment", 1)[-1]
        handler = getattr(self, f"_t_{task}", None)
        if handler is None and task.startswith("fix_"):
            handler = self._t_fix
        text = handler(prompt, assignment) if handler else "Acknowledged."
        return text, len(prompt) // 4, len(text) // 4

